from support import CWVTest
class MetricTests(CWVTest):
    def rate(self,name,value):return self.module('metrics').rating(name,value)
    def assess(self,values,**kw):return self.module('metrics').assess_field(values,**kw)
    def test_lcp_good_boundary(self):self.assertEqual(self.rate('LCP',2500),'good')
    def test_lcp_above_good(self):self.assertEqual(self.rate('LCP',2500.1),'needs_improvement')
    def test_lcp_poor_boundary(self):self.assertEqual(self.rate('LCP',4000),'needs_improvement')
    def test_lcp_poor(self):self.assertEqual(self.rate('LCP',4001),'poor')
    def test_inp_good_boundary(self):self.assertEqual(self.rate('INP',200),'good')
    def test_inp_poor_boundary(self):self.assertEqual(self.rate('INP',500),'needs_improvement')
    def test_cls_good_boundary(self):self.assertEqual(self.rate('CLS',0.1),'good')
    def test_cls_poor_boundary(self):self.assertEqual(self.rate('CLS',0.25),'needs_improvement')
    def test_cls_poor(self):self.assertEqual(self.rate('CLS',0.25001),'poor')
    def test_missing_not_zero(self):self.assertEqual(self.rate('LCP',None),'unknown')
    def test_true_not_numeric(self):self.assertEqual(self.rate('INP',True),'unknown')
    def test_nan_unknown(self):self.assertEqual(self.rate('CLS',float('nan')),'unknown')
    def test_negative_unknown(self):self.assertEqual(self.rate('LCP',-1),'unknown')
    def test_infinity_unknown(self):self.assertEqual(self.rate('LCP',float('inf')),'unknown')
    def test_cls_zero_valid(self):self.assertEqual(self.rate('CLS',0),'good')
    def test_tbt_not_cwv_metric(self):self.assertEqual(self.rate('TBT',100),'supplementary')
    def test_three_field_metrics_good(self):self.assertEqual(self.assess({'LCP':2000,'CLS':0.05,'INP':150})['assessment'],'pass')
    def test_one_bad_field_metric_fails(self):self.assertEqual(self.assess({'LCP':3000,'CLS':0.05,'INP':150})['assessment'],'not_pass')
    def test_inp_missing_strict_unknown(self):self.assertEqual(self.assess({'LCP':2000,'CLS':0.05})['assessment'],'insufficient_data')
    def test_psi_inp_exception_explicit(self):
        r=self.assess({'LCP':2000,'CLS':0.05},policy='psi');self.assertEqual(r['assessment'],'pass_inp_unavailable');self.assertFalse(r['all_three_observed'])
    def test_missing_lcp_never_psi_pass(self):self.assertEqual(self.assess({'CLS':0.05,'INP':100},policy='psi')['assessment'],'insufficient_data')
    def test_tbt_does_not_fill_inp(self):self.assertEqual(self.assess({'LCP':2000,'CLS':0.05,'TBT':100})['assessment'],'insufficient_data')
